/**
 * The compiled font module is what the build makes from the committed
 * sources, those sources are the files the README names, and the tables fit
 * their budget.
 *
 * Running the build again here and requiring the committed file byte for byte
 * is what keeps `src/fonts/latin.ts` honest: it is generated, it cannot be
 * reviewed by reading it, and a hand edit or a stale build would otherwise
 * ship unnoticed.
 */

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import { describe, expect, it } from 'vitest';
import {
	EXTRAS,
	LICENCE_FILE,
	LICENCE_SHA256,
	OUTPUT,
	SOURCES,
	buildFonts,
} from '../../scripts/build-fonts.js';
import { FONT_LICENCE, PLEX_SANS_BOLD, PLEX_SANS_REGULAR } from '../../src/fonts/latin.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

/** The compiled data for both weights may take at most this much of a minified bundle. */
const BUDGET = 60_000;

const sha256 = (bytes: Uint8Array | string): string =>
	createHash('sha256').update(bytes).digest('hex');

describe('the font sources', () => {
	const readme = readFileSync(resolve(root, 'fonts/README.md'), 'utf8');

	it('are the files the build and the README name', () => {
		for (const source of SOURCES) {
			const digest = sha256(readFileSync(resolve(root, source.file)));
			expect(digest, source.file).toBe(source.sha256);
			expect(readme, source.file).toContain(digest);
		}
		const licence = sha256(readFileSync(resolve(root, LICENCE_FILE)));
		expect(licence).toBe(LICENCE_SHA256);
		expect(readme).toContain(licence);
		expect(readme).toContain(
			'https://github.com/IBM/plex/releases/download/%40ibm/plex-sans%401.1.0/ibm-plex-sans.zip',
		);
		expect(readme).toContain(`${EXTRAS.length} characters`);
	});
});

describe('the compiled font module', () => {
	it('is exactly what the build makes', async () => {
		const { text, weights } = await buildFonts();
		expect(text).toBe(readFileSync(resolve(root, OUTPUT), 'utf8'));
		expect(weights.map((w) => w.source.id)).toEqual(['plex-sans-regular', 'plex-sans-bold']);
		expect(text.startsWith('/**\n * GENERATED by scripts/build-fonts.ts')).toBe(true);
	}, 30_000);

	it('fits its budget in a minified bundle', async () => {
		const measure = async (names: string): Promise<number> => {
			const result = await esbuild.build({
				stdin: {
					contents: `import { ${names} } from './src/fonts/latin.ts'; globalThis.kept = [${names}];`,
					resolveDir: root,
					loader: 'ts',
				},
				bundle: true,
				minify: true,
				write: false,
				metafile: true,
				format: 'iife',
				legalComments: 'none',
			});
			let bytes = 0;
			for (const output of Object.values(result.metafile.outputs)) {
				for (const [path, input] of Object.entries(output.inputs)) {
					if (path.endsWith('src/fonts/latin.ts')) bytes += input.bytesInOutput;
				}
			}
			return bytes;
		};
		const tables = await measure('PLEX_SANS_REGULAR, PLEX_SANS_BOLD');
		const withLicence = await measure('PLEX_SANS_REGULAR, PLEX_SANS_BOLD, FONT_LICENCE');
		// Measured when the subset was settled: 56,130 bytes, and 60,499 with
		// the licence text a page that shows it also carries.
		expect(tables).toBeLessThanOrEqual(BUDGET);
		expect(withLicence - tables).toBeLessThan(4_500);
	}, 30_000);

	it('carries the licence and nothing the house style forbids', () => {
		expect(FONT_LICENCE).toContain('SIL Open Font License, Version 1.1');
		expect(FONT_LICENCE).toContain('Copyright © 2017 IBM Corp.');
		const text = readFileSync(resolve(root, OUTPUT), 'utf8');
		for (const banned of ['—', '–', '‘', '’', '“', '”', '→', '•']) {
			expect(text).not.toContain(banned);
		}
		// The base64 tables are long enough that a word could turn up by
		// chance, and the offline file's build test would then fail on it.
		const lowered = text.toLowerCase();
		for (const word of [
			'unlock',
			'unleash',
			'empower',
			'supercharge',
			'seamless',
			'effortless',
			'robust',
			'leverage',
		]) {
			expect(lowered).not.toContain(word);
		}
	});

	it('describes each table it exports', () => {
		for (const data of [PLEX_SANS_REGULAR, PLEX_SANS_BOLD]) {
			expect(data.unitsPerEm).toBe(1000);
			expect(data.data.length % 4).toBe(0);
			expect(data.length).toBeGreaterThan(data.data.length / 2);
		}
	});
});
